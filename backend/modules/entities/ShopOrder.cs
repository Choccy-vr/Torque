namespace Torque.Shop;
// One purchase, waiting in the fulfilment queue until an admin ships it. Names and
// prices are copied at purchase time so later item edits don't rewrite history.
public class ShopOrder
{
    public Guid Id { get; set; }
    public Guid UserId { get; set; }

    // Null once the item / variant is deleted.
    public Guid? ShopItemId { get; set; }
    public Guid? VariantId { get; set; }

    public string ItemName { get; set; } = null!;
    public string? VariantName { get; set; }
    public int Quantity { get; set; }
    public int UnitPrice { get; set; }
    public int TotalPrice { get; set; }
    public string Region { get; set; } = null!;
    // Bought as the daily item (so it skipped the level lock).
    public bool ViaDaily { get; set; }

    public ShopOrderStatus Status { get; set; } = ShopOrderStatus.pending;

    // The address the buyer confirmed at checkout, copied from HCA. The only addresses
    // Torque stores — only admin endpoints return them.
    public string ShipName { get; set; } = "";
    public string ShipLine1 { get; set; } = "";
    public string? ShipLine2 { get; set; }
    public string ShipCity { get; set; } = "";
    public string? ShipState { get; set; }
    public string? ShipPostalCode { get; set; }
    public string ShipCountry { get; set; } = "";

    public string? UserNote { get; set; }

    // Generated by the checkout dialog; unique per user, so a double-submit returns the
    // first order instead of buying twice.
    public Guid ClientRequestId { get; set; }

    public string? TrackingReference { get; set; }
    public string? AdminNote { get; set; }
    public Guid? FulfilledByUserId { get; set; }
    public DateTime? FulfilledAt { get; set; }
    public DateTime? RefundedAt { get; set; }

    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
}

public enum ShopOrderStatus
{
    pending,
    fulfilled,
    refunded
}
